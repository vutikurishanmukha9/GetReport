"""
Understand-Anything Schema Exporter for GetReport Backend.
Transforms a DatasetGraphStore into a 100% compliant Understand-Anything KnowledgeGraph
JSON schema ({version, kind, project, nodes, edges, layers, tour}) capable of being loaded
directly by any Understand-Anything CLI viewer (npx understand-anything-viewer) or plugin.
"""
from __future__ import annotations
import json
import logging
import os
from datetime import datetime
from typing import Dict, List, Any, Optional
import networkx as nx

from app.services.understand_anything.layer_detector import detect_dataset_layers
from app.services.understand_anything.tour_generator import generate_dataset_audit_tour

logger = logging.getLogger(__name__)

# Mapping from GetReport entity_type to Understand-Anything canonical NodeType (27 allowed types)
ENTITY_TO_UA_NODE_TYPE = {
    "Dataset": "document",
    "RawSource": "document",
    "FeatureColumn": "schema",
    "Column": "schema",
    "DataQualityIssue": "concept",
    "IntegrityViolation": "concept",
    "SecurityRisk": "resource",
    "PIIExposure": "resource",
    "SQLSourceTable": "table",
    "SQLTargetView": "table",
    "SQLCTE": "module",
    "StatisticalProfile": "concept",
}

# Mapping from GetReport relation_type to Understand-Anything canonical EdgeType (38 allowed types)
RELATION_TO_UA_EDGE_TYPE = {
    "CONTAINS_COLUMN": "contains",
    "HAS_QUALITY_ISSUE": "validates",
    "HAS_PII_RISK": "depends_on",
    "CORRELATED_WITH": "related",
    "AFFECTS_CONFIDENCE": "transforms",
    "READS_FROM": "reads_from",
    "WRITES_TO": "writes_to",
    "FEEDS_INTO": "transforms",
    "JOINS_WITH": "related",
    "DEFINES_SCHEMA": "defines_schema",
    "DEPENDS_ON": "depends_on",
}


def export_to_understand_anything_schema(
    G: nx.MultiDiGraph,
    project_name: str = "Dataset Audit",
    description: str = "Automated data quality and lineage knowledge graph generated by GetReport.",
    analysis_results: Optional[Dict[str, Any]] = None
) -> Dict[str, Any]:
    """
    Constructs a valid Understand-Anything KnowledgeGraph JSON structure.
    """
    if not G:
        return {
            "version": "1.0.0",
            "kind": "codebase",
            "project": {"name": project_name, "languages": ["SQL", "Parquet"], "frameworks": ["Polars", "DuckDB"], "description": description, "analyzedAt": datetime.now().isoformat(), "gitCommitHash": "head"},
            "nodes": [],
            "edges": [],
            "layers": [],
            "tour": []
        }

    ua_nodes: List[Dict[str, Any]] = []
    for nid, attrs in G.nodes(data=True):
        raw_type = attrs.get("entity_type", "FeatureColumn")
        ua_type = ENTITY_TO_UA_NODE_TYPE.get(raw_type, "concept")

        deg = G.degree(nid)
        complexity = "complex" if deg >= 5 else "moderate" if deg >= 2 else "simple"

        summary = attrs.get("summary") or attrs.get("description")
        if not summary:
            if raw_type == "FeatureColumn":
                summary = f"Column with {attrs.get('null_percentage', 0.0)}% nulls. Data type: {attrs.get('data_type', 'Unknown')}."
            elif raw_type == "DataQualityIssue":
                summary = f"Quality issue: {attrs.get('issue_type', 'Anomaly')}. Severity: {attrs.get('severity', 'medium')}."
            elif raw_type == "SecurityRisk":
                summary = f"Sensitive PII field flagged for governance compliance."
            else:
                summary = f"Entity: {attrs.get('name', nid)}"

        tags = list(attrs.get("tags", []))
        if attrs.get("community_label"):
            tags.append(str(attrs["community_label"]))
        if attrs.get("benford_status"):
            tags.append(f"Benford:{attrs['benford_status']}")

        ua_nodes.append({
            "id": nid,
            "type": ua_type,
            "name": str(attrs.get("name") or attrs.get("column_name") or nid),
            "filePath": str(attrs.get("source_file", "dataset.csv")),
            "summary": summary,
            "tags": tags,
            "complexity": complexity,
        })

    ua_edges: List[Dict[str, Any]] = []
    for u, v, k, attrs in G.edges(keys=True, data=True):
        rel = attrs.get("relation_type", attrs.get("relation", "DEPENDS_ON"))
        ua_edge_type = RELATION_TO_UA_EDGE_TYPE.get(rel, "depends_on")
        weight = float(attrs.get("weight", 1.0))
        # Normalize weight to 0.0 - 1.0 range
        norm_weight = min(max(weight / 5.0, 0.1), 1.0)

        ua_edges.append({
            "source": u,
            "target": v,
            "type": ua_edge_type,
            "direction": "forward",
            "weight": round(norm_weight, 2),
            "description": f"{rel} relationship"
        })

    # Detect layers and tours
    layers = detect_dataset_layers(G)
    tour = generate_dataset_audit_tour(G, analysis_results=analysis_results)

    return {
        "version": "1.0.0",
        "kind": "codebase",
        "project": {
            "name": project_name,
            "languages": ["SQL", "Parquet", "Python"],
            "frameworks": ["Polars", "DuckDB", "GreatExpectations"],
            "description": description,
            "analyzedAt": datetime.now().isoformat(),
            "gitCommitHash": "getreport-audit"
        },
        "nodes": ua_nodes,
        "edges": ua_edges,
        "layers": layers,
        "tour": tour
    }


def write_understand_anything_data_dir(
    G: nx.MultiDiGraph,
    output_dir: str,
    project_name: str = "Dataset Audit",
    analysis_results: Optional[Dict[str, Any]] = None
) -> str:
    """
    Writes the graph into a standard Understand-Anything data directory (.ua/knowledge-graph.json).
    """
    ua_data = export_to_understand_anything_schema(
        G,
        project_name=project_name,
        analysis_results=analysis_results
    )
    os.makedirs(output_dir, exist_ok=True)
    target_file = os.path.join(output_dir, "knowledge-graph.json")
    with open(target_file, "w", encoding="utf-8") as f:
        json.dump(ua_data, f, indent=2, default=str)

    return target_file
