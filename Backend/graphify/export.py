"""
Multi-format Enterprise Export Engine for Graphify.
Supports Neo4j Cypher scripts, standard GraphML, node-link JSON, vector SVG, and interactive HTML.
"""
from __future__ import annotations
import os
import json
from typing import Dict, List, Any, Optional
import networkx as nx

from graphify.exporters.html import to_html
from graphify.exporters.svg import to_svg


def to_cypher(G: nx.Graph, output_path: str) -> str:
    """
    Exports a NetworkX graph as a deterministic Neo4j Cypher script.
    """
    os.makedirs(os.path.dirname(os.path.abspath(output_path)), exist_ok=True)
    lines: List[str] = [
        "// ========================================================",
        "// Neo4j Cypher Export generated by GetReport Graphify Engine",
        "// ========================================================",
        ":begin"
    ]

    # Create Nodes
    for n, d in G.nodes(data=True):
        entity_type = str(d.get("entity_type") or "Entity").replace(" ", "_")
        # Sanitize attributes
        props = {"id": str(n)}
        for k, v in d.items():
            if k != "id" and isinstance(v, (str, int, float, bool)):
                props[str(k)] = v
        prop_str = ", ".join(f"{k}: {json.dumps(v)}" for k, v in props.items())
        lines.append(f"CREATE (:{entity_type} {{{prop_str}}});")

    # Create Edges
    for u, v, d in G.edges(data=True):
        raw_rel = str(d.get("relation") or d.get("relation_type") or "CONNECTED_TO")
        rel_clean = raw_rel.upper().replace(" ", "_").replace("-", "_")
        weight = float(d.get("weight", 1.0))
        lines.append(
            f"MATCH (a {{id: {json.dumps(str(u))}}}), (b {{id: {json.dumps(str(v))}}}) "
            f"CREATE (a)-[:{rel_clean} {{weight: {weight}}}]->(b);"
        )

    lines.append(":commit")
    lines.append("")

    with open(output_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))

    return output_path


def to_graphml(G: nx.Graph, output_path: str) -> str:
    """
    Exports a NetworkX graph to standard GraphML format,
    sanitizing metadata for strict XML compatibility.
    """
    os.makedirs(os.path.dirname(os.path.abspath(output_path)), exist_ok=True)
    clean_g = nx.Graph()

    for n, d in G.nodes(data=True):
        clean_attrs = {}
        for k, v in d.items():
            if v is None:
                continue
            if isinstance(v, (int, float, str, bool)):
                clean_attrs[str(k)] = v
            else:
                clean_attrs[str(k)] = str(v)
        clean_g.add_node(str(n), **clean_attrs)

    for u, v, d in G.edges(data=True):
        clean_attrs = {}
        for k, v in d.items():
            if v is None:
                continue
            if isinstance(v, (int, float, str, bool)):
                clean_attrs[str(k)] = v
            else:
                clean_attrs[str(k)] = str(v)
        clean_g.add_edge(str(u), str(v), **clean_attrs)

    nx.write_graphml(clean_g, output_path)
    return output_path


def to_json(G: nx.Graph, output_path: str) -> str:
    """
    Exports a NetworkX graph as a standard node-link JSON payload.
    """
    os.makedirs(os.path.dirname(os.path.abspath(output_path)), exist_ok=True)
    from networkx.readwrite import json_graph
    data = json_graph.node_link_data(G)
    with open(output_path, "w", encoding="utf-8") as f:
        json.dump(data, f, indent=2)
    return output_path
